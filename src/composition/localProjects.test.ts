import { afterEach, expect, it } from "vitest";
import { IDBFactory } from "fake-indexeddb";
import { createLocalProjects } from "./localProjects";
import { IndexedDbRepository } from "../backend/indexeddb";
import { buildDataRouter } from "../backend/routes";
import { createInternalDispatch } from "../adapter/internalDispatch";
import { createHttpAdapter } from "../adapter/api";
import { C, newId } from "../domain/concepts";
const close: (() => Promise<void>)[] = [];
afterEach(async () => { await Promise.all(close.splice(0).map(dispose => dispose())); });
function fixture() {
  const suffix = newId(), factory = new IDBFactory();
  const options = { factory, catalogName: `projects-${suffix}`, existingWorkspaceName: `existing-${suffix}`, namespace: suffix };
  const create = () => { const service = createLocalProjects(options); close.push(service.close); return service; };
  return { options, create };
}
it("preserves the current saved workspace, isolates facts/settings and keeps old adapters scoped after switching", async () => {
  const { options, create } = fixture();
  const repository = new IndexedDbRepository(options.existingWorkspaceName, options.factory);
  const old = createHttpAdapter(createInternalDispatch(buildDataRouter(repository)));
  const concept = { id: newId(), label: "已有独立笔记", types: [C.concept] };
  await old.mutate({ put: [concept] }); const saved = await old.load(); await repository.close();
  const service = create(), first = await service.adapter.load(), current = await service.adapter.open(first.activeProjectId);
  expect(await current.load()).toEqual(saved);
  const id = newId(), commandId = newId();
  await service.adapter.execute({ type: "project.create", id, name: "物理" }, commandId);
  const second = await service.adapter.open(id), blank = await second.load();
  expect(blank.concepts.some(item => item.participants)).toBe(false);
  expect(blank.concepts.find(item => item.id === concept.id)).toBeUndefined(); expect(blank.settings.focusId).toBeNull();
  const next = { id: newId(), label: "牛顿第一定律", types: [C.concept] };
  await second.mutate({ put: [next] });
  await current.mutate({ put: [{ ...concept, label: "切换后的旧适配器写入" }] });
  expect((await second.load()).concepts.find(item => item.id === concept.id)).toBeUndefined();
  const settings = await current.load(); await current.saveSettings({ ...settings.settings, depth: 8, focusId: concept.id });
  expect((await second.load()).settings.depth).toBe(blank.settings.depth);
  const media = await current.upload(new File(["project-specific media"], "background.png", { type: "image/png" }));
  await expect(second.mediaInfo(media.id)).rejects.toMatchObject({ fault: { code: "NOT_FOUND" } });
  expect(await (await current.mediaContent(media.id)).text()).toBe("project-specific media");
  await service.close();
  const reopened = create(), catalog = await reopened.adapter.load();
  expect(catalog.activeProjectId).toBe(id);
  expect((await (await reopened.adapter.open(id)).load()).concepts.find(item => item.id === next.id)).toEqual(next);
  const original = await reopened.adapter.open(first.activeProjectId);
  expect((await original.load()).settings.focusId).toBe(concept.id);
  expect((await original.load()).concepts.find(item => item.id === concept.id)?.label).toBe("切换后的旧适配器写入");
});
it("durably replays project commands across connections, rejects reused IDs and stale rename versions", async () => {
  const { create } = fixture(), a = create(), b = create(); await a.adapter.load(); await b.adapter.load();
  const operation = { type: "project.create" as const, id: newId(), name: "同名项目" }, commandId = newId();
  const commits = await Promise.all([a.adapter.execute(operation, commandId), b.adapter.execute(operation, commandId)]);
  expect(commits.filter(commit => !commit.replayed)).toHaveLength(1);
  expect((await a.adapter.load()).projects).toHaveLength(2);
  await expect(a.adapter.execute({ ...operation, name: "另一份命令" }, commandId)).rejects.toMatchObject({ fault: { code: "IDEMPOTENCY_KEY_REUSED" } });
  await a.adapter.execute({ type: "project.rename", id: operation.id, expectedVersion: 1, name: "重命名" }, newId());
  await expect(b.adapter.execute({ type: "project.rename", id: operation.id, expectedVersion: 1, name: "过期改名" }, newId())).rejects.toMatchObject({ fault: { code: "VERSION_CONFLICT" } });
  const replay = await b.adapter.execute(operation, commandId); expect(replay.replayed).toBe(true);
  expect((await b.adapter.load()).projects.find(project => project.id === operation.id)?.name).toBe("重命名");
  await expect(b.adapter.open(newId())).rejects.toMatchObject({ fault: { code: "NOT_FOUND" } });
});
